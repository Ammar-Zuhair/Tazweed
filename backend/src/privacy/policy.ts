import type { Config } from "../config.js";
export function policy(c: Config) {
  const approved = !!(
    c.STORE_LEGAL_NAME &&
    c.STORE_SUPPORT_PHONE &&
    c.PRIVACY_CONTACT_EMAIL &&
    c.PRIVACY_POLICY_VERSION &&
    c.PRIVACY_POLICY_APPROVED_AT &&
    c.PRIVACY_PERSONAL_RETENTION_DAYS !== undefined &&
    c.TRANSACTION_RETENTION_DAYS !== undefined &&
    c.PRIVACY_SECURITY_RETENTION_DAYS !== undefined &&
    c.PRIVACY_BACKUP_RETENTION_DAYS !== undefined &&
    c.PRIVACY_REQUEST_TARGET_DAYS !== undefined
  );
  return {
    approved,
    version: c.PRIVACY_POLICY_VERSION,
    approvedAt: c.PRIVACY_POLICY_APPROVED_AT,
    legalName: c.STORE_LEGAL_NAME,
    supportPhone: c.STORE_SUPPORT_PHONE,
    email: c.PRIVACY_CONTACT_EMAIL,
    personalDays: c.PRIVACY_PERSONAL_RETENTION_DAYS ?? null,
    transactionDays: c.TRANSACTION_RETENTION_DAYS ?? null,
    securityDays: c.PRIVACY_SECURITY_RETENTION_DAYS ?? null,
    backupDays: c.PRIVACY_BACKUP_RETENTION_DAYS ?? null,
    targetDays: c.PRIVACY_REQUEST_TARGET_DAYS ?? null,
  };
}
